/** Where a glyph design came from. Carried by candidates and added glyphs. */

export interface Region {
  readonly height: number;
  readonly width: number;
  readonly x: number;
  readonly y: number;
}

/** What a generation run was: the strategy, the model behind it, and whether it was live. */
export interface GenerationSource {
  readonly createdAt: string;
  /** The model behind the strategy, when one was used. */
  readonly model?: string;
  /** True when the output was replayed from a recorded run, not produced live. */
  readonly recorded?: boolean;
  readonly runId: string;
  /** The generation strategy that produced it, for example "procedural". */
  readonly strategy: string;
}

export type Provenance =
  | { readonly origin: "manual" }
  | ({ readonly origin: "generated" } & GenerationSource)
  | {
      readonly origin: "reconstructed";
      readonly evidenceId: string;
      /** Observed lettering was seen in the evidence. Inferred lettering was not. */
      readonly basis: "observed" | "inferred";
      readonly region?: Region;
      readonly confidence?: number;
      /** What drew inferred lettering. Observed lettering has none: it was traced. */
      readonly inferredBy?: GenerationSource;
    };

export const isUnconfirmed = (provenance: Provenance) =>
  provenance.origin === "generated" ||
  (provenance.origin === "reconstructed" && provenance.basis === "inferred");

/** The three marks for work made after the source font. */
export type DesignMark = "edited" | "observed" | "unconfirmed";

/**
 * How a design made after the source font is marked, from where it came from
 * and where its candidate stands. Accepted work is in the face and takes the
 * solid mark of an edit, whatever made it. Until then, generated or inferred
 * work is unconfirmed, and lettering traced from evidence is observed. A
 * candidate that was never proposed, or was rejected, is not accepted either.
 * Hand work has no candidate to wait on, so it is always an edit.
 */
export const designMark = (
  provenance: Provenance,
  status: "accepted" | "proposed" | "rejected" | undefined
): DesignMark => {
  if (status === "accepted" || provenance.origin === "manual") {
    return "edited";
  }
  return isUnconfirmed(provenance) ? "unconfirmed" : "observed";
};

/**
 * The frame around a design drawn large. A rejected candidate is neither in
 * the face nor waiting to be, so it has no frame of its own. Anything else
 * is framed by its mark.
 */
export const designFrame = (
  provenance: Provenance,
  status: "accepted" | "proposed" | "rejected" | undefined
): DesignMark | "none" =>
  status === "rejected" ? "none" : designMark(provenance, status);

/** The four things the interface calls where a design came from. */
export type DesignOrigin = "generated" | "inferred" | "manual" | "observed";

/** Reconstructed lettering is observed or inferred. Nothing is called just reconstructed. */
export const designOrigin = (provenance: Provenance): DesignOrigin =>
  provenance.origin === "reconstructed" ? provenance.basis : provenance.origin;

/** How a run made what it made: replayed from a recorded run, drawn by a model as it ran, or built by rule. */
export type Making = "model" | "recorded" | "rule";

/**
 * A recorded run is always called recorded, whatever model drew it first:
 * the replay called no model. Asked before anything else, so no place can
 * take a recording for live output.
 */
export const makingOf = ({
  model,
  recorded,
}: Pick<GenerationSource, "model" | "recorded">): Making => {
  if (recorded) {
    return "recorded";
  }
  return model ? "model" : "rule";
};

const strategyWords = ({ model, strategy }: GenerationSource) =>
  model ? `${strategy} strategy with ${model}` : `${strategy} strategy`;

/** What drew inferred lettering, when the provenance says. */
const inferenceNote = (by: GenerationSource | undefined) => {
  if (!by) {
    return "";
  }
  return makingOf(by) === "recorded"
    ? ` Drawn by a recorded run of the ${strategyWords(by)}, replayed. Not live model output.`
    : ` Drawn by the ${strategyWords(by)}.`;
};

/**
 * Where a design came from, in plain sentences. This is the one place the
 * interface's words for provenance are written.
 */
export const describeProvenance = (provenance: Provenance): string => {
  if (provenance.origin === "manual") {
    return "Drawn by hand.";
  }
  if (provenance.origin === "generated") {
    return makingOf(provenance) === "recorded"
      ? `Replayed from a recorded run of the ${strategyWords(provenance)}. Not live model output.`
      : `Generated by the ${strategyWords(provenance)}.`;
  }
  return provenance.basis === "observed"
    ? "Reconstructed from lettering observed in the evidence."
    : `Inferred. This lettering was not seen in the evidence.${inferenceNote(provenance.inferredBy)}`;
};
