/** Provenance in words, for a candidate or an added glyph. */
import { isUnconfirmed, type Provenance } from "~/typeface/provenance";

/** Where a design came from, in one plain sentence. Recorded output is always called recorded. */
export const provenanceNote = (provenance: Provenance): string => {
  if (provenance.origin === "manual") {
    return "Drawn by hand.";
  }
  if (provenance.origin === "generated") {
    const by = provenance.model
      ? `${provenance.strategy} strategy with ${provenance.model}`
      : `${provenance.strategy} strategy`;
    return provenance.recorded
      ? `Replayed from a recorded run of the ${by}. Not live model output.`
      : `Generated by the ${by}.`;
  }
  return provenance.basis === "observed"
    ? "Reconstructed from lettering observed in the evidence."
    : "Inferred. This lettering was not seen in the evidence.";
};

/** The mark a design carries: dotted until it is confirmed, solid once it is. */
export const provenanceMark = (provenance: Provenance) =>
  isUnconfirmed(provenance) ? "unconfirmed" : "edited";
