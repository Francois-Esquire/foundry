import { describe, expect, it } from "vitest";
import {
  describeProvenance,
  designFrame,
  designMark,
  designOrigin,
  makingOf,
  type Provenance,
  standingOf,
} from "~/typeface/provenance";

const GENERATED: Provenance = {
  createdAt: "2026-11-10T09:00:00.000Z",
  origin: "generated",
  runId: "run-1",
  strategy: "procedural",
};
const OBSERVED: Provenance = {
  basis: "observed",
  evidenceId: "photograph",
  origin: "reconstructed",
};
const INFERRED: Provenance = { ...OBSERVED, basis: "inferred" };

const IN_THE_EVIDENCE = /(observed|seen) in the evidence/;
const NOT_IN_THE_EVIDENCE = /not (observed|seen) in the evidence/;
const NOT_SEEN = /not (observed|seen)/;
const SAYS_INFERRED = /inferred/i;

describe("the mark of a design made after the source font", () => {
  it("tells observed lettering from generated and inferred work until it is accepted", () => {
    expect(designMark(OBSERVED, "proposed")).toBe("observed");
    expect(designMark(INFERRED, "proposed")).toBe("unconfirmed");
    expect(designMark(GENERATED, "proposed")).toBe("unconfirmed");
  });

  it("gives accepted work the solid mark of work in the face, whatever made it", () => {
    for (const provenance of [OBSERVED, INFERRED, GENERATED]) {
      expect(designMark(provenance, "accepted")).toBe("edited");
    }
  });

  it("treats a design that was never proposed, or was rejected, as not accepted", () => {
    expect(designMark(OBSERVED, undefined)).toBe("observed");
    expect(designMark(OBSERVED, "rejected")).toBe("observed");
    expect(designMark(INFERRED, undefined)).toBe("unconfirmed");
    expect(designMark(GENERATED, "rejected")).toBe("unconfirmed");
  });

  it("marks hand work as an edit wherever it stands", () => {
    expect(designMark({ origin: "manual" }, "proposed")).toBe("edited");
    expect(designMark({ origin: "manual" }, undefined)).toBe("edited");
  });

  it("frames a design by its mark, and gives a rejected one no frame of its own", () => {
    expect(designFrame(OBSERVED, undefined)).toBe("observed");
    expect(designFrame(OBSERVED, "proposed")).toBe("observed");
    expect(designFrame(INFERRED, "proposed")).toBe("unconfirmed");
    expect(designFrame(GENERATED, "accepted")).toBe("edited");
    for (const provenance of [OBSERVED, INFERRED, GENERATED]) {
      expect(designFrame(provenance, "rejected")).toBe("none");
    }
  });
});

describe("where a design came from, in words", () => {
  it("says a recorded run is recorded, never live", () => {
    expect(
      describeProvenance({
        ...GENERATED,
        model: "Ideogram Vector",
        recorded: true,
      })
    ).toBe(
      "Replayed from a recorded run of the procedural strategy with Ideogram Vector. Not live model output."
    );
  });

  it("names the strategy that generated a design", () => {
    expect(describeProvenance(GENERATED)).toBe(
      "Generated by the procedural strategy."
    );
  });

  it("keeps observed and inferred lettering apart", () => {
    expect(
      describeProvenance({
        basis: "observed",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Reconstructed from lettering observed in the evidence.");
    expect(
      describeProvenance({
        basis: "inferred",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Inferred. This lettering was not seen in the evidence.");
  });

  it("says observed lettering was in the evidence and inferred lettering was not, whatever the words", () => {
    const observed = describeProvenance(OBSERVED);
    const inferred = describeProvenance(INFERRED);
    expect(observed).toMatch(IN_THE_EVIDENCE);
    expect(observed).not.toMatch(NOT_SEEN);
    expect(observed).not.toMatch(SAYS_INFERRED);
    expect(inferred).toMatch(NOT_IN_THE_EVIDENCE);
    expect(inferred).toMatch(SAYS_INFERRED);
  });

  it("says what drew inferred lettering, and that a recorded run was replayed", () => {
    expect(
      describeProvenance({
        basis: "inferred",
        evidenceId: "e",
        inferredBy: {
          createdAt: "2026-11-10T09:00:00.000Z",
          model: "Ideogram Vector",
          recorded: true,
          runId: "run-1",
          strategy: "vector-model",
        },
        origin: "reconstructed",
      })
    ).toBe(
      "Inferred. This lettering was not seen in the evidence. Drawn by a recorded run of the vector-model strategy with Ideogram Vector, replayed. Not live model output."
    );
  });

  it("says the same of a recorded run whatever strategy and model made it", () => {
    const generated = { ...GENERATED, model: "a model", strategy: "vector" };
    expect(describeProvenance(generated)).toBe(
      "Generated by the vector strategy with a model."
    );
    expect(describeProvenance({ ...generated, recorded: true })).toBe(
      "Replayed from a recorded run of the vector strategy with a model. Not live model output."
    );
  });

  it("names hand work", () => {
    expect(describeProvenance({ origin: "manual" })).toBe("Drawn by hand.");
  });
});

describe("the origin of a design", () => {
  it("is one of four: by hand, generated, observed or inferred", () => {
    expect(designOrigin({ origin: "manual" })).toBe("manual");
    expect(designOrigin(GENERATED)).toBe("generated");
    expect(designOrigin(OBSERVED)).toBe("observed");
    expect(designOrigin(INFERRED)).toBe("inferred");
  });
});

describe("how a run made its output", () => {
  it("calls a recorded run recorded, whatever model drew it first", () => {
    expect(makingOf({ model: "a model", recorded: true })).toBe("recorded");
    expect(makingOf({ recorded: true })).toBe("recorded");
  });

  it("tells a model that drew as the run went from a rule", () => {
    expect(makingOf({ model: "a model" })).toBe("model");
    expect(makingOf({ model: "a model", recorded: false })).toBe("model");
    expect(makingOf({})).toBe("rule");
  });
});

describe("where a design stands, in a mark and in words", () => {
  const OUT = "It stays out of the face and of any export.";

  it("marks an observed candidate apart from a generated or inferred one", () => {
    expect(standingOf(OBSERVED, "proposed")).toEqual({
      kind: "observed",
      text: `Observed in the evidence, not accepted. ${OUT}`,
    });
    expect(standingOf(GENERATED, "proposed")).toEqual({
      kind: "unconfirmed",
      text: `Generated, not accepted. ${OUT}`,
    });
    expect(standingOf(INFERRED, "proposed")).toEqual({
      kind: "unconfirmed",
      text: `Inferred, not accepted. ${OUT}`,
    });
  });

  it("gives accepted work the solid mark and still says where it came from", () => {
    expect(standingOf(OBSERVED, "added")).toEqual({
      kind: "edited",
      text: "Observed in the evidence, accepted into the face",
    });
    expect(standingOf(GENERATED, "added")).toEqual({
      kind: "edited",
      text: "Generated, accepted into the face",
    });
  });

  it("always says inferred, waiting or in the face", () => {
    for (const standing of ["proposed", "added", "edited"] as const) {
      const { text } = standingOf(INFERRED, standing);
      expect(text).toMatch(SAYS_INFERRED);
      expect(standingOf(OBSERVED, standing).text).not.toMatch(SAYS_INFERRED);
    }
  });

  it("marks a hand-made candidate as the edit it is, and reads work of unknown origin as hand work", () => {
    expect(standingOf({ origin: "manual" }, "proposed")).toEqual({
      kind: "edited",
      text: `Candidate, not accepted. ${OUT}`,
    });
    expect(standingOf(undefined, "proposed")).toEqual({
      kind: "unconfirmed",
      text: `Candidate, not accepted. ${OUT}`,
    });
    expect(standingOf(undefined, "edited").text).toBe(
      standingOf({ origin: "manual" }, "edited").text
    );
  });
});
