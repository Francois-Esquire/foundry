import { describe, expect, it } from "vitest";
import { candidateMark, provenanceNote } from "~/studio/provenance-notes";
import type { Provenance } from "~/typeface/provenance";

const generated: Provenance = {
  createdAt: "2026-11-10T09:00:00.000Z",
  origin: "generated",
  runId: "run-1",
  strategy: "procedural",
};

describe("provenance in words", () => {
  it("says a recorded run is recorded, never live", () => {
    expect(
      provenanceNote({ ...generated, model: "Ideogram Vector", recorded: true })
    ).toBe(
      "Replayed from a recorded run of the procedural strategy with Ideogram Vector. Not live model output."
    );
  });

  it("names the strategy that generated a design", () => {
    expect(provenanceNote(generated)).toBe(
      "Generated by the procedural strategy."
    );
  });

  it("keeps observed and inferred lettering apart", () => {
    expect(
      provenanceNote({
        basis: "observed",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Reconstructed from lettering observed in the evidence.");
    expect(
      provenanceNote({
        basis: "inferred",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Inferred. This lettering was not seen in the evidence.");
  });

  it("says what drew inferred lettering, and that a recorded run was replayed", () => {
    expect(
      provenanceNote({
        basis: "inferred",
        evidenceId: "e",
        inferredBy: {
          createdAt: "2026-11-10T09:00:00.000Z",
          model: "Ideogram Vector",
          recorded: true,
          runId: "run-1",
          strategy: "vector-model",
        },
        origin: "reconstructed",
      })
    ).toBe(
      "Inferred. This lettering was not seen in the evidence. Drawn by a recorded run of the vector-model strategy with Ideogram Vector, replayed. Not live model output."
    );
  });

  const observed: Provenance = {
    basis: "observed",
    evidenceId: "e",
    origin: "reconstructed",
  };

  it("marks an observed candidate apart from a generated or inferred one", () => {
    expect(candidateMark(observed, "proposed")).toEqual({
      kind: "observed",
      text: "Observed in the evidence, not accepted",
    });
    expect(candidateMark(generated, "proposed")).toEqual({
      kind: "unconfirmed",
      text: "Generated, not accepted",
    });
    expect(
      candidateMark({ ...observed, basis: "inferred" }, "proposed")
    ).toEqual({ kind: "unconfirmed", text: "Inferred, not accepted" });
  });

  it("gives accepted work the solid mark and still says where it came from", () => {
    expect(candidateMark(observed, "accepted")).toEqual({
      kind: "edited",
      text: "Observed in the evidence, accepted",
    });
    expect(candidateMark(generated, "accepted")).toEqual({
      kind: "edited",
      text: "Generated, accepted",
    });
  });
});
