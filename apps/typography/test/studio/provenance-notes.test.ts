import { describe, expect, it } from "vitest";
import { provenanceMark, provenanceNote } from "~/studio/provenance-notes";
import type { Provenance } from "~/typeface/provenance";

const generated: Provenance = {
  createdAt: "2026-11-10T09:00:00.000Z",
  origin: "generated",
  runId: "run-1",
  strategy: "procedural",
};

describe("provenance in words", () => {
  it("says a recorded run is recorded, never live", () => {
    expect(
      provenanceNote({ ...generated, model: "Ideogram Vector", recorded: true })
    ).toBe(
      "Replayed from a recorded run of the procedural strategy with Ideogram Vector. Not live model output."
    );
  });

  it("names the strategy that generated a design", () => {
    expect(provenanceNote(generated)).toBe(
      "Generated by the procedural strategy."
    );
  });

  it("keeps observed and inferred lettering apart", () => {
    expect(
      provenanceNote({
        basis: "observed",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Reconstructed from lettering observed in the evidence.");
    expect(
      provenanceNote({
        basis: "inferred",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("Inferred. This lettering was not seen in the evidence.");
  });

  it("marks generated and inferred work as unconfirmed, the rest as edits", () => {
    expect(provenanceMark(generated)).toBe("unconfirmed");
    expect(provenanceMark({ origin: "manual" })).toBe("edited");
    expect(
      provenanceMark({
        basis: "observed",
        evidenceId: "e",
        origin: "reconstructed",
      })
    ).toBe("edited");
  });
});
