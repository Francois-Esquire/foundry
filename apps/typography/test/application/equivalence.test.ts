/**
 * A screen and a command are the same use cases. Two applications alike in
 * every means start from the same project. One is driven through the session
 * a screen holds, the other is given the command, and the two projects are
 * compared whole. Where the application will not go on, the sentence the
 * command throws is the sentence the screen shows.
 */
import { afterEach, describe, expect, it } from "vitest";
import type { ApplicationMeans } from "~/application/means";
import { codes } from "../generate/helpers/session";
import {
  BANNER,
  BANNER_TEXT,
  closeTwins,
  DEVANAGARI_SUBSET,
  LATIN_HOLDOUT,
  labelOnScreen,
  markOnScreen,
  ONE_PIXEL,
  projectOf,
  refusalOf,
  STOREFRONT_COMPLETION,
  type Twin,
  twins,
  twinsWithoutTheRun,
} from "./helpers/twins";

/** Starting the font engine to make a new face can outlast the default limit. */
const ENGINE_TIMEOUT = 120_000;

let pair: { readonly command: Twin; readonly screen: Twin } | undefined;

afterEach(async () => {
  if (pair) {
    await closeTwins(pair);
    pair = undefined;
  }
});

const started = async (open: () => ReturnType<typeof twins> = twins) => {
  pair = await open();
  expect(projectOf(pair.screen)).toEqual(projectOf(pair.command));
  return pair;
};

describe("a screen and a command leave the same project", () => {
  it("after characters are generated by rule", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.generate();
    await session.run({
      characters: codes("éèñ"),
      faceId: screen.faceId,
      kind: "characters",
      strategy: "procedural",
    });
    await command.app.generate({
      characters: "é è U+00F1",
      faceId: command.faceId,
      kind: "characters",
      strategy: "procedural",
    });
    expect(projectOf(screen).candidates).toHaveLength(3);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("after the recorded Latin holdout is replayed", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.generate();
    await session.listRecorded();
    await session.run({
      entryId: `${LATIN_HOLDOUT}#vector-model`,
      faceId: screen.faceId,
      kind: "recorded",
    });
    await command.app.generate({
      faceId: command.faceId,
      kind: "recorded",
      output: "vector-model",
      recordedRun: LATIN_HOLDOUT,
    });
    expect(projectOf(screen).candidates).toHaveLength(6);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("after the script extension is run, then added", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.scriptExtension();
    await session.listSource();
    await session.run(screen.faceId);
    session.add(screen.faceId);
    const run = await command.app.generate({
      faceId: command.faceId,
      kind: "script-extension",
      plan: "devanagari-subset",
      recordedRun: DEVANAGARI_SUBSET,
    });
    await command.app.accept({ run: run.runId });
    expect(projectOf(screen).head).toBe(1);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it(
    "after the storefront's observed letters are proposed to a new face",
    async () => {
      const { command, screen } = await started();
      const session = screen.app.places.screen.reconstruct();
      await markOnScreen(session, screen, BANNER);
      await labelOnScreen(session, BANNER_TEXT);
      session.setDestination({ familyName: "Banner", kind: "new" });
      await session.propose();
      await command.app.reconstruct({
        destination: { familyName: "Banner", kind: "new" },
        photograph: command.photograph.artifactId,
        region: BANNER,
        text: BANNER_TEXT,
      });
      expect(projectOf(screen).faces).toHaveLength(2);
      expect(projectOf(screen).candidates.length).toBeGreaterThan(8);
      expect(projectOf(screen)).toEqual(projectOf(command));
    },
    ENGINE_TIMEOUT
  );

  it("after the alphabet is completed from the recorded run", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.reconstruct();
    await markOnScreen(session, screen, BANNER);
    await labelOnScreen(session, BANNER_TEXT);
    session.setDestination({ faceId: screen.faceId, kind: "existing" });
    await session.propose();
    session.updateCompletionDraft({ strategy: "recorded-run" });
    await session.listRecorded();
    await session.complete();
    session.proposeInferred();
    const recovered = await command.app.reconstruct({
      complete: { kind: "recorded", recordedRun: STOREFRONT_COMPLETION },
      destination: { faceId: command.faceId, kind: "existing" },
      photograph: command.photograph.artifactId,
      region: BANNER,
      text: BANNER_TEXT,
    });
    expect(recovered.inferred).toHaveLength(15);
    expect(projectOf(screen).candidates).toHaveLength(
      recovered.observed.length + recovered.inferred.length
    );
    expect(projectOf(screen)).toEqual(projectOf(command));
  });
});

describe("a refusal reads the same on a screen and from a command", () => {
  it("when a model strategy is asked without a key", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.generate();
    await session.run({
      characters: codes("é"),
      faceId: screen.faceId,
      kind: "characters",
      strategy: "vector-model",
    });
    const shown = session.getState().activity?.failure?.reason;
    const thrown = await refusalOf(
      command.app.generate({
        characters: "é",
        faceId: command.faceId,
        kind: "characters",
        strategy: "vector-model",
      })
    );
    expect(shown).toBe(
      "No fal API key was supplied, so this model cannot be called. Add a key to use it."
    );
    expect(thrown).toBe(shown);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("when the face already holds the extension", async () => {
    const { command, screen } = await started();
    const extension = {
      kind: "script-extension",
      plan: "devanagari-subset",
      recordedRun: DEVANAGARI_SUBSET,
    } as const;
    // Each project is given the extension by the command, so the screen's
    // session has run nothing for this face when it is asked.
    for (const { app, faceId } of [command, screen]) {
      const run = await app.generate({ ...extension, faceId });
      await app.accept({ run: run.runId });
    }
    const session = screen.app.places.screen.scriptExtension();
    await session.listSource();
    await session.run(screen.faceId);
    const { run } = session.getState().faces.get(screen.faceId) ?? {};
    const shown = run?.status === "failed" ? run.reason : undefined;
    const thrown = await refusalOf(
      command.app.generate({ ...extension, faceId: command.faceId })
    );
    expect(shown).toBeTruthy();
    expect(thrown).toBe(shown);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("when the region holds no lettering", async () => {
    const { command, screen } = await started();
    const session = screen.app.places.screen.reconstruct();
    await markOnScreen(session, screen, ONE_PIXEL);
    session.setDestination({ faceId: screen.faceId, kind: "existing" });
    await session.propose();
    const { proposalProblem, readingProblem } = session.getState();
    const shown = readingProblem ?? proposalProblem;
    const thrown = await refusalOf(
      command.app.reconstruct({
        destination: { faceId: command.faceId, kind: "existing" },
        photograph: command.photograph.artifactId,
        region: ONE_PIXEL,
      })
    );
    expect(shown).toBeTruthy();
    expect(thrown).toBe(shown);
    expect(projectOf(screen).candidates).toEqual([]);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("when the model cannot be reached", async () => {
    const { command, screen } = await started(() =>
      twins({
        modelFetch: () => Promise.reject(new TypeError("fetch failed")),
        providerKey: "a-key",
      })
    );
    const session = screen.app.places.screen.generate();
    await session.run({
      characters: codes("é"),
      faceId: screen.faceId,
      kind: "characters",
      strategy: "vector-model",
    });
    const shown = session.getState().activity?.failure?.reason;
    const thrown = await refusalOf(
      command.app.generate({
        characters: "é",
        faceId: command.faceId,
        kind: "characters",
        strategy: "vector-model",
      })
    );
    expect(shown).toBe("fetch failed");
    expect(thrown).toBe(shown);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("when the font engine cannot make the new face", async () => {
    const { command, screen } = await started(() =>
      twins({
        builder: {
          blankFont: () =>
            Promise.reject(new Error("The font engine did not start.")),
        } as unknown as ApplicationMeans["builder"],
      })
    );
    const session = screen.app.places.screen.reconstruct();
    await markOnScreen(session, screen, BANNER);
    session.setDestination({ familyName: "Banner", kind: "new" });
    await session.propose();
    const shown = session.getState().proposalProblem;
    const thrown = await refusalOf(
      command.app.reconstruct({
        destination: { familyName: "Banner", kind: "new" },
        photograph: command.photograph.artifactId,
        region: BANNER,
      })
    );
    expect(shown).toBe("The font engine did not start.");
    expect(thrown).toBe(shown);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });

  it("when the recorded run does not exist", async () => {
    const { command, screen } = await started(twinsWithoutTheRun);
    const session = screen.app.places.screen.scriptExtension();
    await session.listSource();
    const { source } = session.getState();
    const shown = source.status === "failed" ? source.reason : undefined;
    const thrown = await refusalOf(
      command.app.generate({
        faceId: command.faceId,
        kind: "script-extension",
        plan: "devanagari-subset",
        recordedRun: DEVANAGARI_SUBSET,
      })
    );
    expect(shown).toBeTruthy();
    expect(thrown).toBe(shown);
    expect(projectOf(screen)).toEqual(projectOf(command));
  });
});
